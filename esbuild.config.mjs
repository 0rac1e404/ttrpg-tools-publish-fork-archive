import esbuild from "esbuild";
import process from "process";
import { mkdirSync } from "fs";

const prod = process.argv[2] === "production";
const watch = process.argv[2] === "watch";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/`;

mkdirSync("dist", { recursive: true });

/** @type {import("esbuild").BuildOptions} */
const pluginOpts = {
  entryPoints: ["src/main.ts"],
  bundle: true,
  outfile: "main.js",
  format: "cjs",
  target: "es2020",
  platform: "browser",
  sourcemap: prod ? false : "inline",
  minify: prod,
  banner: { js: banner },
  external: ["obsidian", "fs", "path", "node:fs", "node:path"]
};

/** @type {import("esbuild").BuildOptions} */
const staticOpts = {
  entryPoints: ["src/static-entry.ts"],
  bundle: true,
  outfile: "zoom-map-static.js",
  format: "iife",
  target: "es2020",
  platform: "browser",
  sourcemap: prod ? false : "inline",
  minify: prod,
  banner: { js: "/* TTRPG Tools Static Bundle - Digital Garden / Eleventy compatible */" },
};

if (watch) {
  const pluginCtx = await esbuild.context(pluginOpts);
  const staticCtx = await esbuild.context(staticOpts);
  await pluginCtx.watch();
  await staticCtx.watch();
  console.log("watching plugin + static bundle...");
} else {
  await esbuild.build(pluginOpts);
  await esbuild.build(staticOpts);
  console.log("built plugin (main.js) + static bundle (zoom-map-static.js)");
}
